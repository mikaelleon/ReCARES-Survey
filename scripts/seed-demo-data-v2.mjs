function makeTraits(phase, slot) {
  const tenant = slot === 'tenant';
  const role = slot === 'tenant'
    ? (chance(0.72) ? 5 : 6)
    : slot === 'rentOut'
      ? weighted([[2, 45], [3, 40], [1, 15]])
      : weighted([[1, 55], [2, 6], [3, 8], [4, 31]]);
  const prof = PHASE_PROFILE[phase];
  const baseAge = {
    '18-24': tenant ? 8 : 3, '25-34': tenant ? 30 : 18, '35-44': 26, '45-54': tenant ? 17 : 24,
    '55-64': tenant ? 12 : 17, '65+': tenant ? 4 : 10,
  };
  // Shift the whole age distribution: positive ageShift favors older bands, negative favors younger ones.
  const ageWeights = Object.fromEntries(AGES.map((a, i) => [a, Math.max(0.5, baseAge[a] * Math.exp(prof.ageShift * (i - 2.5) * 0.35))]));
  const age = weighted(AGES.map((a) => [a, ageWeights[a]]));
  const ageIdx = AGES.indexOf(age);
  const digital = clamp(0.9 - ageIdx * 0.1 + prof.digital + gauss() * 0.18, 0.02, 1);
  const interest = clamp(0.3 + digital * 0.5 + gauss() * 0.12, 0, 1);
  const pwdP = clamp((age === '65+' ? 0.2 : age === '55-64' ? 0.1 : 0.03) * prof.pwd, 0.01, 0.3);
  return {
    phase, slot, role, tenant, age, ageWeights, digital, interest, pwdP,
    stay: prof.stay, size: prof.size,
    absentee: role === 2 || role === 3,
    noDevice: digital < 0.1 && chance(0.4),
    bias: gauss() * 0.5, // persistent lean to agree or disagree
    pwd: false,
    yes: false,
  };
}

function chooseSingle(q, r, a) {
  const visible = visibleOptions(q, a).map((o) => String(o.id));
  const pairs = (W[q.code] ? W[q.code](r, a) : []).filter(([id]) => visible.includes(String(id)));
  const id = pairs.length ? weighted(pairs) : pick(visible);
  return q.numericValues ? Number(id) : id;
}

function chooseMulti(q, r, a) {
  const visible = visibleOptions(q, a).map((o) => o.id);
  const excl = q.exclusiveId ?? visible.find((id) => NONE_IDS.has(id));
  const probs = MULTI_P[q.code];
  let picks;
  if (probs) {
    picks = visible.filter((id) => id !== excl && probs[id] && chance(clamp(probs[id](r, a), 0, 0.95)));
    if (q.code === 'F8' && r.interest < 0.22 && chance(0.5)) picks = [];
  } else {
    const pool = visible.filter((id) => id !== excl);
    picks = sample(pool, between(1, Math.min(3, pool.length)));
  }
  if (q.maxSelect != null) picks = picks.slice(0, q.maxSelect);
  if (picks.length === 0) picks = excl ? [excl] : [pick(visible)];
  return picks;
}

// ---- open problems (O1) ------------------------------------------------------
// Phase 3 has no water supply and a vehicles-blocking-driveways problem. Other phases mostly report
// low water pressure. Garbage, pets and neighbor disputes are the next most common everywhere.
// Security patrol is deliberately the least reported.

const O1_BASE = {
  water_supply: 0.38, electricity_power: 0.2, garbage_collection: 0.42, street_lights: 0.2, roads_drainage: 0.22,
  noise_curfew: 0.2, parking: 0.2, security_patrol: 0.04, renovation_permits: 0.12,
  pet_animal: 0.36, facilities_amenities: 0.14, neighbor_disputes: 0.42, street_event_closures: 0.11,
};
const O1_PHASE3 = { water_supply: 0.96, parking: 0.64, garbage_collection: 0.44, pet_animal: 0.34, neighbor_disputes: 0.33 };
const WATER_OUTAGE = [
  'Frequent water interruptions or no water supply', 'Water stays out for many hours or days',
  'No updates on when the water will return', 'No alternative water source during outages (tanker or refill)',
  'Water interruptions happen without advance notice', 'Unclear who to contact or how to report a water problem',
];

function buildO1(q, r) {
  const out = {};
  const p3 = r.phase === 'Phase 3';
  if (chance(0.07)) return { [q.code]: ['none_of_these'] };
  let ids = (q.categories ?? []).map((c) => c.id).filter((id) => chance((p3 && O1_PHASE3[id]) || O1_BASE[id] || 0.1));
  if (ids.length === 0) ids = [p3 ? 'water_supply' : pick(['garbage_collection', 'pet_animal', 'neighbor_disputes'])];
  ids = sample(ids, Math.min(ids.length, 5));
  const details = {};
  for (const id of ids) {
    const cat = q.categories.find((c) => c.id === id);
    const items = cat.items.filter((i) => i !== 'Other');
    if (id === 'water_supply') {
      details[id] = p3
        ? [...new Set([pick(WATER_OUTAGE.slice(0, 2)), ...sample(WATER_OUTAGE, between(1, 3))])]
        : chance(0.9) ? ['Low water pressure'] : [pick(items)];
    } else if (id === 'parking' && p3) {
      details[id] = [...new Set(['Vehicles blocking driveways or roads', ...(chance(0.5) ? sample(items, 1) : [])])];
    } else {
      details[id] = sample(items, between(1, 3));
    }
  }
  out[q.code] = ids;
  out[`${q.code}Details`] = details;
  if (chance(0.05)) {
    out[q.code].push('other');
    out[`${q.code}_other`] = pick(['Dust from the unpaved road nearby', 'Poor mobile signal inside the subdivision']);
  }
  return out;
}

function buildAnswers(r, preset) {
  const a = { ...preset };
  const likertBias = r.bias;

  for (const q of INST.questions) {
    if (a[q.code] !== undefined) continue;
    if (!questionVisible(q, a)) continue;

    const code = q.code;
    if (q.type === 'likert') {
      if (q.allowNA && chance(0.05)) {
        a[code] = 'not_applicable';
        continue;
      }
      const centre = likertCentre(code, r, q.scale);
      a[code] = clamp(Math.round(centre + likertBias * (q.scale === 'likelihood' ? 0.2 : 1) + gauss() * 0.9), 1, 5);
    } else if (q.type === 'single') {
      a[code] = chooseSingle(q, r, a);
      if (code === 'A4') r.pwd = a.A4 === 'yes';
    } else if (q.type === 'multi') {
      if (code === 'CC2') {
        const chosen = (a.CC1 ?? []).filter((id) => !NONE_IDS.has(id));
        a.CC2 = sample(chosen, Math.min(chosen.length, q.maxSelect ?? 3, between(1, 3)));
      } else if (code === 'CC1' && chance(0.22)) {
        a.CC1 = ['none'];
      } else if (code === 'B1' && r.noDevice) {
        a.B1 = ['none'];
      } else {
        a[code] = chooseMulti(q, r, a);
      }
    } else if (q.type === 'number') {
      a[code] = clamp(Math.round(7 + Math.abs(gauss()) * 9 + (chance(0.15) ? between(10, 25) : 0)), q.min ?? 0, Math.min(q.max ?? 60, 60));
    } else if (q.type === 'text') {
      const pool = TEXT[code];
      if (pool && chance(TEXT_P[code] ?? 0.3)) a[code] = pick(pool);
    } else if (q.type === 'nested_multi') {
      Object.assign(a, buildO1(q, r));
    }

    // Keep dependent answers consistent with the one just given.
    if (code === 'CC2b') {
      const from = a.CC2 ?? [];
      if (!from.includes(a.CC2b)) a.CC2b = pick(from);
    }
    if (code === 'CH3' && (a.CH3 ?? []).includes('none') && a.CH3.length > 1) a.CH3 = ['none'];
    if (code === 'CH4') {
      const from = (a.CH3 ?? []).filter((id) => id !== 'none');
      a.CH4 = from.length ? (from.includes(a.CH4) ? a.CH4 : pick(from)) : 'none';
    }
  }
  const out = normalizeAnswers(INST, a);

  // The v2 draft has no F2 or C1 to C3, but the dashboard's feature-interest and street-closure widgets
  // still read them. Seed them so those widgets show data instead of "No answers".
  const score = (centre) => clamp(Math.round(centre + r.bias + gauss() * 0.9), 1, 5);
  out.F2 = chance(0.06) ? 1 : clamp(Math.round(1 + 4 * clamp(r.interest + gauss() * 0.13, 0, 1)), 1, 5);
  out.C1 = weighted([['neither', 50], ['affected', 30], ['requested', 10], ['both', 10]]);
  const asked = out.C1 !== 'neither';
  out.C2 = !asked && chance(0.45) ? 'not_applicable' : score(asked ? 2.8 : 2.9);
  out.C3 = !asked && chance(0.35) ? 'not_applicable' : score(asked ? 2.7 : 2.9);
  return out;
}

// ---- generate responses ----------------------------------------------------

function slotsFor({ total, tenants, rentOut }) {
  return shuffle([
    ...Array(tenants).fill('tenant'),
    ...Array(rentOut).fill('rentOut'),
    ...Array(total - tenants - rentOut).fill('owner'),
  ]);
}

const responses = [];
for (const [phase, plan] of Object.entries(PLAN)) {
  const people = slotsFor(plan).map((slot) => makeTraits(phase, slot));
  // Open-ended, digital, engaged respondents say yes to the interview more often.
  const yesSet = new Set(
    people
      .map((r) => ({ r, s: r.digital * 0.5 + rnd() * 0.7 }))
      .sort((p, q) => q.s - p.s)
      .slice(0, plan.yes)
      .map((x) => x.r),
  );
  const pwdSeed = pick(people); // every phase has at least one respondent with a disability or mobility limitation
  for (const r of people) {
    r.yes = yesSet.has(r);
    const date = weighted(DAY_WEIGHTS);
    const clock = submitClock(date);
    const preset = { A1: r.role, A2: phase, IV1: r.yes ? 'yes' : 'no' };
    if (r.slot === 'rentOut') preset.A13 = 'yes';
    else if (r.role >= 1 && r.role <= 3) preset.A13 = weighted([['no', 93], ['prefer_not_to_say', 7]]);
    if (r === pwdSeed) {
      preset.A4 = 'yes';
      r.pwd = true;
    }
    const answers = buildAnswers(r, preset);
    const hasPhoneOnly = Array.isArray(answers.B1) && answers.B1.includes('smartphone') && !answers.B1.includes('laptop_desktop');
    responses.push({
      phase,
      r,
      clock,
      doc: {
        responseId: '',
        submittedDate: date,
        status: 'complete',
        lastStepReached: INST.steps.length,
        deviceClass: hasPhoneOnly || answers.B1?.includes('none') ? 'phone' : chance(0.55) ? 'computer' : 'phone',
        answers,
        instrumentVersion: INSTRUMENT_VERSION,
        demoSeed: true,
      },
    });
  }
}

// With small phases a category can land on zero by chance, and a zero reads as broken in the analytics.
// Make sure every O1 category appears in every phase (street closures at least twice), and keep security
// patrol to exactly one mention per phase so it stays the least reported problem.
{
  const o1 = INST.questions.find((q) => q.code === 'O1');
  const cats = Object.fromEntries(o1.categories.map((c) => [c.id, c]));
  const detailFor = (id, phase) => {
    const items = cats[id].items.filter((i) => i !== 'Other');
    if (id === 'water_supply') return phase === 'Phase 3' ? [pick(WATER_OUTAGE.slice(0, 2))] : ['Low water pressure'];
    return sample(items, between(1, 2));
  };
  for (const phase of Object.keys(PLAN)) {
    const rs = responses.filter((x) => x.phase === phase);
    const has = (x, id) => Array.isArray(x.doc.answers.O1) && x.doc.answers.O1.includes(id);
    const add = (x, id) => {
      const a = x.doc.answers;
      if (!Array.isArray(a.O1) || a.O1.includes('none_of_these')) {
        a.O1 = [];
        a.O1Details = {};
      }
      a.O1.push(id);
      a.O1Details = { ...(a.O1Details ?? {}), [id]: detailFor(id, phase) };
    };
    const drop = (x, id) => {
      const a = x.doc.answers;
      a.O1 = a.O1.filter((v) => v !== id);
      delete a.O1Details?.[id];
      if (a.O1.length === 0) {
        a.O1 = ['none_of_these'];
        delete a.O1Details;
      }
    };
    const secured = rs.filter((x) => has(x, 'security_patrol'));
    secured.slice(1).forEach((x) => drop(x, 'security_patrol'));
    for (const id of Object.keys(cats)) {
      const need = id === 'street_event_closures' ? 2 : 1;
      let have = rs.filter((x) => has(x, id)).length;
      for (const x of shuffle(rs)) {
        if (have >= need) break;
        if (!has(x, id) && (x.doc.answers.O1 ?? []).length < 4) {
          add(x, id);
          have += 1;
        }
      }
    }
  }
}

// Chronological order so ids and the dashboard's submission numbers line up.
responses.sort((x, y) => stampMs(x.doc.submittedDate, x.clock) - stampMs(y.doc.submittedDate, y.clock));
responses.forEach((x) => {
  x.doc.responseId = uuid();
});

