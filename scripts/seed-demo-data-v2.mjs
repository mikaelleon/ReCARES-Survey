/** Mean agreement (1-5) for an item, from the respondent's traits. Item wording is not parsed; the prefix sets the topic. */
function likertCentre(code, r, scale) {
  const prefix = code.replace(/[0-9].*$/, '');
  if (scale === 'likelihood') {
    const off = { F1: 0.1, F3: r.tenant ? 0.08 : 0.02, F4: -0.14, F5: 0.06, F6: r.pwd ? 0.15 : -0.12 }[code] ?? 0;
    return 1 + 4 * clamp(r.interest + off, 0, 1);
  }
  switch (prefix) {
    case 'B':
      return code === 'B8' ? 4.1 - r.digital * 1.6 : 1.8 + r.digital * 3;
    case 'F':
      return 2 + r.interest * 3;
    case 'S':
      return 3.1 + r.bias * 0.3;
    case 'P':
      return 3.2;
    case 'R':
      return code === 'R1' || code === 'R5' ? 2.2 + r.digital * 2 : code === 'R6' ? 3.6 : 3.1 + (r.interest - 0.5);
    case 'H':
      return 3.0;
    case 'T':
    case 'TO':
      return code.startsWith('TO') ? 3.0 : 3.1;
    case 'OM':
      return 3.2;
    case 'CC':
      return 3.2;
    case 'HR':
      return 3.0 + (r.tenant ? -0.3 : 0.3);
    case 'CH':
      return 2.9 + r.digital * 0.6;
    case 'AC':
      return r.pwd ? 3.9 : 2.5;
    case 'C':
      return 2.9;
    default:
      return 3;
  }
}

